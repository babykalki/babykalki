    class Admin(http.server.BaseHTTPRequestHandler):
        def _ok(self):
            return admin_token and hmac.compare_digest(self.headers.get("X-Admin-Token", ""), admin_token)

        def _send(self, code, obj):
            b = json.dumps(obj, default=str).encode()
            self.send_response(code); self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(b))); self.end_headers(); self.wfile.write(b)

        def do_GET(self):
            if not self._ok():
                return self._send(403, {"error": "forbidden"})
            if self.path == "/stats":
                with lock:
                    return self._send(200, lib.stats())
            if self.path == "/approvals/pending":          # v0.5: the founder's /bk-approve page
                with lock:
                    return self._send(200, lib.pending_approvals())
            self._send(404, {"error": "not found"})

        def do_POST(self):
            if not self._ok():
                return self._send(403, {"error": "forbidden"})
            if self.path == "/approvals/decide":           # v0.5: ONLY the founder's /bk-approve page calls this
                try:
                    n = int(self.headers.get("Content-Length") or 0)
                    body = json.loads(self.rfile.read(min(n, 65536)) or b"{}")
                except Exception:
                    return self._send(400, {"error": "bad json"})
                with lock:
                    try:
                        return self._send(200, lib.decide_approval(str(body.get("request_id", "")), str(body.get("decision", "")),
                                                                   str(body.get("founder", "")), str(body.get("shown_sha256", ""))))
                    except Refused as e:
                        return self._send(409, {"result": "REFUSED", "reason": str(e)})
            if self.path == "/snapshot":
                with lock:
                    try:
                        return self._send(200, lib.snapshot())
                    except Exception as e:
                        return self._send(500, {"error": str(e)})
            self._send(404, {"error": "not found"})

        def log_message(self, *a):
            pass

    adm = http.server.ThreadingHTTPServer((host, admin_port), Admin)
    threading.Thread(target=adm.serve_forever, daemon=True).start()
    print(f"library: MCP on http://{host}:{port}/mcp, admin on {host}:{admin_port}, {len(ids)} citizen tokens", flush=True)
    m.run("streamable-http", host=host, port=port)    # loopback only


