class Library:
    def __init__(self, db_path, schema_path, cards_dir, citizens_dir, backups_dir, restored_marker,
                 min_free_mb=500, scanner=None, diary_root="/data/diary"):
        self.db_path, self.dir = db_path, os.path.dirname(os.path.abspath(db_path))
        self.cards, self.citizens, self.backups = cards_dir, citizens_dir, backups_dir
        self.diary_root, self.min_free_mb = diary_root, min_free_mb
        self.scanner = scanner or Scanner()
        if not os.path.exists(db_path) and not os.path.exists(restored_marker):
            # Never start an EMPTY Library on a fresh disk unless bk_backup.py said so (restored, or remote really empty).
            raise SystemExit(f"NOT RESTORED: {db_path} is missing and {restored_marker} does not exist. "
                             "Run bk_backup.py restore first (the supervisor does this).")
        os.makedirs(self.dir, exist_ok=True)
        self.db = lb.Database(db_path)
        self.c = lb.Connection(self.db)
        self.c.execute(open(schema_path).read())          # CREATE … IF NOT EXISTS — idempotent
        self.log = ChainWriter(os.path.join(self.dir, "changes.jsonl"))
        self.approvals_path = os.path.join(self.dir, "approvals.jsonl")
        self.approvals = ChainWriter(self.approvals_path)

    # ---------- guards ----------
    def _guard_secret(self, **fields):
        for k, v in fields.items():
            kinds = self.scanner.check(v if isinstance(v, str) else json.dumps(v, default=str))
            if kinds:
                raise Refused(f"REFUSED: '{k}' looks like it contains a secret ({', '.join(kinds)}). "
                              "Remove it and use the secret's NAME (e.g. ZAI_API_KEY).")

    def _guard_disk(self):
        free = shutil.disk_usage(self.dir).free // (1024 * 1024)
        if free < self.min_free_mb:
            raise Refused(f"REFUSED: only {free} MB free. Writes stop before the disk fills. Tell the founder.")

    def _need(self, who, allowed, tool):
        if who not in allowed:
            raise Refused(f"REFUSED: {tool} is for {', '.join(sorted(allowed))} only; you are '{who}'.")

    def _log(self, who, action, payload):
        self.log.append({"at": now().isoformat() + "Z", "who": who, "action": action, "payload": payload})

    def _rows(self, q, params=None):
        r = self.c.execute(q, params or {})
        out = []
        while r.has_next():
            out.append(r.get_next())
        return out

    def _tx(self, steps):
        """All-or-nothing. steps = [(query, params, expected_rows or None)]. A step that changes a different number of
        rows than expected rolls everything back and REFUSES (no silent no-ops)."""
        self.c.execute("BEGIN TRANSACTION")
        try:
            for q, p, expect in steps:
                rows = self._rows(q, p)
                if expect is not None and len(rows) != expect:
                    raise Refused(f"REFUSED: expected to change {expect} row(s), would change {len(rows)}. Nothing was written.")
            self.c.execute("COMMIT")
        except Exception:
            self.c.execute("ROLLBACK")
            raise

    def _fact(self, fid):
        r = self._rows("MATCH (f:Fact {id:$id}) RETURN f.status, f.retired_reason", {"id": fid})
        return r[0] if r else None

    def _explain_not_live(self, fid):
        f = self._fact(fid)
        if not f:
            return f"REFUSED: there is no fact '{fid}'. Use recall to find the right id."
        if f[0] == "superseded":
            return f"REFUSED: '{fid}' is superseded — {self._resolve(fid)}"
        return f"REFUSED: '{fid}' is {f[0]}, not live."

    # ---------- read path (everyone) ----------
    def _resolve(self, fid):
        """Follow SUPERSEDES from an old fact to the end of the chain."""
        chain, head, seen = [fid], fid, {fid}
        while True:
            nxt = self._rows("MATCH (n:Fact)-[:SUPERSEDES]->(o:Fact {id:$id}) RETURN n.id, n.status, n.retired_reason", {"id": head})
            if not nxt:
                return {"result": "BROKEN_CHAIN", "id": fid, "chain": chain,
                        "note": f"{head} is superseded but nothing supersedes it — tell the Librarian."}
            head, status, why = nxt[0]
            if head in seen:
                return {"result": "BROKEN_CHAIN", "id": fid, "chain": chain, "note": "cycle in the chain"}
            seen.add(head); chain.append(head)
            if status == "live":
                return {"result": "SUPERSEDED", "id": fid, "live_id": head, "chain": chain, "note": "Use live_id, not the old id."}
            if status == "retired":
                return {"result": "RETIRED", "id": fid, "retired_id": head, "chain": chain, "reason": why,
                        "note": "The newest version was retired: it no longer applies. Substitute nothing."}

    def _sources(self, fid):
        return [r[0] for r in self._rows("MATCH (f:Fact {id:$id})-[:FROM_SOURCE]->(s:Source) RETURN s.url", {"id": fid})]

    def recall(self, query, topic=None, limit=10, who="?"):
        """FOUND (ranked, with total and sources) / MISS (with coverage) / SUPERSEDED (→ live_id) / RETIRED."""
        query = (query or "").strip()
        limit = max(1, min(int(limit or 10), 50))
        if re.fullmatch(r"F-[0-9a-f]{8}", query):
            hit = self._rows("MATCH (f:Fact {id:$id}) RETURN f.id, f.text, f.status, f.topic, f.level, f.instrument, "
                             "f.verified_at, f.retired_reason", {"id": query})
            if not hit:
                return {"result": "MISS", "query": query, "coverage": self.coverage(), "note": "No fact with that id."}
            fid, text, status, tp, lvl, instr, ver, why = hit[0]
            if status == "live":
                return {"result": "FOUND", "total": 1, "shown": 1, "facts": [
                    {"id": fid, "text": text, "topic": tp, "level": lvl, "instrument": instr, "verified_at": str(ver),
                     "sources": self._sources(fid)}]}
            if status == "retired":
                return {"result": "RETIRED", "id": fid, "reason": why, "note": "No longer applies. Substitute nothing."}
            return self._resolve(fid)
        q = terms(query)
        q_set = set(q)
        if not q_set:
            return {"result": "MISS", "query": query, "coverage": self.coverage(), "note": "Empty query."}
        cy, p = "MATCH (f:Fact) WHERE f.status='live'", {}
        if topic:
            cy += " AND f.topic=$t"; p["t"] = topic
        scored = []
        phrase = query.lower()
        q_all = terms(query, drop_stop=False)
        q_pairs = set(zip(q_all, q_all[1:]))   # word pairs in the query's order, stop words kept ("our investor")
        for fid, text, tp, lvl, instr, ver in self._rows(cy + " RETURN f.id, f.text, f.topic, f.level, f.instrument, f.verified_at", p):
            t_all = terms(text, drop_stop=False)
            have = set(t_all) | set(terms((tp or "").replace(":", " "), drop_stop=False))
            hit = len(q_set & have)
            if hit:
                # v0.4: + up to 0.3 for word pairs in the query's order, so equal word hits are no longer ordered by the clock
                pairs = len(q_pairs & set(zip(t_all, t_all[1:]))) / len(q_pairs) if q_pairs else 0
                score = hit / len(q_set) + 0.3 * pairs + (0.5 if phrase in (text or "").lower() else 0)
                scored.append((score, str(ver), fid, text, tp, lvl, instr))
        if not scored:
            return {"result": "MISS", "query": query, "searched_terms": sorted(q_set), "coverage": self.coverage(),
                    "note": "Nothing known. Do not guess; say MISS or propose a fact with a source."}
        scored.sort(key=lambda s: (s[0], s[1]), reverse=True)
        top = scored[:limit]
        return {"result": "FOUND", "total": len(scored), "shown": len(top), "searched_terms": sorted(q_set),
                "facts": [{"id": fid, "text": text, "topic": tp, "level": lvl, "instrument": instr, "verified_at": ver,
                           "score": round(sc, 3), "sources": self._sources(fid)} for sc, ver, fid, text, tp, lvl, instr in top]}

    def coverage(self):
        return {t: n for t, n in self._rows("MATCH (f:Fact) WHERE f.status='live' RETURN f.topic, count(f) ORDER BY f.topic")}

    def propose_fact(self, text, topic, instrument, source, who):
        self._guard_secret(text=text, topic=topic, instrument=instrument, source=source)
        self._guard_disk()
        if not (text or "").strip() or not (topic or "").strip():
            raise Refused("REFUSED: a fact needs text and a topic.")
        if not (instrument or "").strip() or not (source or "").strip():
            raise Refused("REFUSED: every fact needs an instrument (how we know) and a source.")
        pid = "P-" + uuid.uuid4().hex[:8]
        self._tx([("CREATE (p:Proposal {id:$id, text:$x, topic:$t, instrument:$i, source:$s, proposed_by:$w, created_at:$at, "
                   "state:'pending'}) RETURN p.id", {"id": pid, "x": text, "t": topic, "i": instrument, "s": source, "w": who, "at": now()}, 1)])
        self._log(who, "propose", {"id": pid, "topic": topic})
        return {"result": "PROPOSED", "id": pid, "proposed_by": who, "note": "The Librarian will review it."}

    # ---------- write path (Librarian only) ----------
    def list_proposals(self, who):
        self._need(who, {"librarian", "librarian_desk"}, "list_proposals")
        return {"result": "OK", "proposals": [dict(zip(["id", "text", "topic", "instrument", "source", "proposed_by"], r)) for r in self._rows(
            "MATCH (p:Proposal {state:'pending'}) RETURN p.id, p.text, p.topic, p.instrument, p.source, p.proposed_by ORDER BY p.created_at")]}

    def commit_proposal(self, proposal_id, who, level="claimed", supersedes=None, reason=None):
        self._need(who, {"librarian"}, "commit_proposal")
        self._guard_disk()
        if level not in ("claimed", "verified"):
            raise Refused("REFUSED: level must be 'claimed' or 'verified'.")
        p = self._rows("MATCH (p:Proposal {id:$id, state:'pending'}) RETURN p.text, p.topic, p.instrument, p.source", {"id": proposal_id})
        if not p:
            raise Refused(f"REFUSED: no pending proposal '{proposal_id}'.")
        text, topic, instr, src = p[0]
        if supersedes:
            if not (reason or "").strip():
                raise Refused("REFUSED: a correction needs a reason.")
            self._guard_secret(reason=reason)
            f = self._fact(supersedes)
            if not f or f[0] != "live":
                raise Refused(self._explain_not_live(supersedes))
        fid, t = "F-" + uuid.uuid4().hex[:8], now()
        st = [("CREATE (f:Fact {id:$id, text:$x, topic:$t, instrument:$i, status:'live', level:$l, created_at:$at, verified_at:$at, "
               "committed_by:$w}) RETURN f.id", {"id": fid, "x": text, "t": topic, "i": instr, "l": level, "at": t, "w": who}, 1),
              ("MERGE (s:Source {id:$s}) ON CREATE SET s.url=$s, s.seen_at=$at RETURN s.id", {"s": src, "at": t}, 1),
              ("MATCH (f:Fact {id:$f}), (s:Source {id:$s}) CREATE (f)-[:FROM_SOURCE]->(s) RETURN f.id", {"f": fid, "s": src}, 1),
              ("MATCH (p:Proposal {id:$id, state:'pending'}) SET p.state='accepted', p.decided_by=$w RETURN p.id", {"id": proposal_id, "w": who}, 1)]
        if supersedes:
            st.append(("MATCH (o:Fact {id:$o, status:'live'}), (n:Fact {id:$n}) SET o.status='superseded' "
                       "CREATE (n)-[:SUPERSEDES {reason:$r, at:$at}]->(o) RETURN o.id", {"o": supersedes, "n": fid, "r": reason, "at": t}, 1))
        self._tx(st)
        self._log(who, "commit", {"proposal": proposal_id, "fact": fid, "level": level, "supersedes": supersedes, "reason": reason})
        return {"result": "COMMITTED", "id": fid, "supersedes": supersedes}

    def reject_proposal(self, proposal_id, reason, who):
        self._need(who, {"librarian"}, "reject_proposal")
        if not (reason or "").strip():
            raise Refused("REFUSED: say why the proposal is rejected.")
        self._guard_secret(reason=reason)
        self._tx([("MATCH (p:Proposal {id:$id, state:'pending'}) SET p.state='rejected', p.decided_by=$w, p.decision_reason=$r RETURN p.id",
                   {"id": proposal_id, "w": who, "r": reason}, 1)])
        self._log(who, "reject", {"proposal": proposal_id, "reason": reason})
        return {"result": "REJECTED", "id": proposal_id}

    def retire_fact(self, fact_id, reason, who):
        self._need(who, {"librarian"}, "retire_fact")
        self._guard_disk()
        if not (reason or "").strip():
            raise Refused("REFUSED: say why the fact no longer applies.")
        self._guard_secret(reason=reason)
        f = self._fact(fact_id)
        if not f or f[0] != "live":
            raise Refused(self._explain_not_live(fact_id))
        self._tx([("MATCH (f:Fact {id:$id, status:'live'}) SET f.status='retired', f.retired_reason=$r RETURN f.id", {"id": fact_id, "r": reason}, 1)])
        self._log(who, "retire", {"fact": fact_id, "reason": reason})
        return {"result": "RETIRED", "id": fact_id}

    def verify_fact(self, fact_id, instrument, who, level=None):
        self._need(who, {"librarian"}, "verify_fact")
        self._guard_disk()
        if not (instrument or "").strip():
            raise Refused("REFUSED: a re-check needs an instrument (how you checked).")
        self._guard_secret(instrument=instrument)
        if level not in (None, "", "claimed", "verified"):
            raise Refused("REFUSED: level must be 'claimed' or 'verified'.")
        f = self._fact(fact_id)
        if not f or f[0] != "live":
            raise Refused(self._explain_not_live(fact_id))
        q = "MATCH (f:Fact {id:$id, status:'live'}) SET f.verified_at=$at, f.instrument = f.instrument + ' | ' + $i"
        p = {"id": fact_id, "at": now(), "i": instrument}
        if level:
            q += ", f.level=$l"; p["l"] = level
        self._tx([(q + " RETURN f.id", p, 1)])        # adds to the instrument history, never replaces it
        self._log(who, "verify", {"fact": fact_id, "level": level})
        return {"result": "VERIFIED", "id": fact_id, "level": level or "unchanged"}

    def render_card(self, citizen, who):
        """Self card = GENERATED from live facts with topic 'card:<citizen>'. Over the cap = refuse + alarm.
        Written to cards/<citizen>.md AND citizens/<citizen>/AGENTS.local.md, which dsh loads next to the citizen's
        AGENTS.md (dsh's default local-instructions file — to verify on dsh 0.2.2-rc.3)."""
        self._need(who, {"librarian"}, "render_card")
        if not NAME_OK.fullmatch(citizen or "") or citizen not in CITIZENS:
            raise Refused(f"REFUSED: unknown citizen '{citizen}'. Use the role name: {', '.join(CITIZENS)}.")
        self._guard_disk()
        rows = self._rows("MATCH (f:Fact) WHERE f.status='live' AND f.topic=$t RETURN f.id, f.text ORDER BY f.created_at", {"t": "card:" + citizen})
        body = (f"# Self card — {citizen} (generated {now().isoformat()}Z from the Library; do not edit by hand)\n"
                + "".join(f"- {t} ({i})\n" for i, t in rows))
        if len(body) > CARD_CAP_CHARS:
            os.makedirs(self.cards, exist_ok=True)
            open(os.path.join(self.cards, f"{citizen}.ALARM"), "w").write(f"card is {len(body)} chars > cap {CARD_CAP_CHARS}\n")
            raise Refused(f"REFUSED: card would be {len(body)} chars (cap {CARD_CAP_CHARS}). Retire or merge card facts.")
        for d, fn in ((self.cards, f"{citizen}.md"), (os.path.join(self.citizens, citizen), "AGENTS.local.md")):
            os.makedirs(d, exist_ok=True)
            tmp = os.path.join(d, f".{fn}.tmp")
            with open(tmp, "w") as f:                       # atomic: temp file, fsync, rename
                f.write(body); f.flush(); os.fsync(f.fileno())
            os.replace(tmp, os.path.join(d, fn))
        self._log(who, "render_card", {"citizen": citizen, "chars": len(body)})
        return {"result": "WRITTEN", "chars": len(body), "cap": CARD_CAP_CHARS, "facts": len(rows)}

    # ---------- tasks (rule 6: every task has an owner and a date) ----------
    def add_task(self, title, owner, due, who):
        self._need(who, {"warden", "steward", "librarian", "community"}, "add_task")
        if who == "community":          # v0.5: the public desk can only hand work to the Steward, clearly labelled
            if owner != "steward":
                raise Refused("REFUSED: the community desk may only create tasks for the steward.")
            title = (title or "").strip()
            if title and not title.startswith("[community]"):
                title = "[community] " + title
            if len(title) > COMMUNITY_TITLE_MAX:
                raise Refused(f"REFUSED: a community task title is at most {COMMUNITY_TITLE_MAX} characters.")
        self._guard_secret(title=title)
        self._guard_disk()
        if owner not in CITIZENS + ("founder",):
            raise Refused(f"REFUSED: owner must be one of {', '.join(CITIZENS + ('founder',))}.")
        try:
            d = dt.date.fromisoformat(due)
        except Exception:
            raise Refused("REFUSED: due must be a date like 2026-11-30.")
        if not (title or "").strip():
            raise Refused("REFUSED: a task needs a title.")
        tid = "T-" + uuid.uuid4().hex[:8]
        self._tx([("CREATE (t:Task {id:$id, title:$x, owner:$o, due:$d, state:'open', created_by:$w, created_at:$at}) RETURN t.id",
                   {"id": tid, "x": title, "o": owner, "d": d, "w": who, "at": now()}, 1)])
        self._log(who, "add_task", {"task": tid, "owner": owner, "due": due})
        return {"result": "ADDED", "id": tid}

    def list_tasks(self, owner=None, state="open"):
        q, p = "MATCH (t:Task) WHERE 1=1", {}
        if owner:
            q += " AND t.owner=$o"; p["o"] = owner
        if state:
            q += " AND t.state=$s"; p["s"] = state
        today = dt.date.today()
        rows = self._rows(q + " RETURN t.id, t.title, t.owner, t.due, t.state ORDER BY t.due", p)
        return {"result": "OK", "total": len(rows), "tasks": [
            {"id": a, "title": b, "owner": c, "due": str(d), "state": e, "overdue": e == "open" and d < today} for a, b, c, d, e in rows]}

    def close_task(self, task_id, state, note, who):
        self._need(who, {"warden", "steward", "librarian", "reviewer", "builder", "scout"}, "close_task")
        if state not in ("done", "dropped"):
            raise Refused("REFUSED: state must be 'done' or 'dropped'.")
        self._guard_secret(note=note)
        t = self._rows("MATCH (t:Task {id:$id}) RETURN t.owner, t.state", {"id": task_id})
        if not t:
            raise Refused(f"REFUSED: there is no task '{task_id}'.")
        if t[0][1] != "open":
            raise Refused(f"REFUSED: task '{task_id}' is already {t[0][1]}.")
        if who not in (t[0][0], "warden"):
            raise Refused(f"REFUSED: only the owner ({t[0][0]}) or the Warden can close this task.")
        self._tx([("MATCH (t:Task {id:$id, state:'open'}) SET t.state=$s, t.note=$n, t.closed_at=$at RETURN t.id",
                   {"id": task_id, "s": state, "n": note or "", "at": now()}, 1)])
        self._log(who, "close_task", {"task": task_id, "state": state})
        return {"result": state.upper(), "id": task_id}

    # ---------- Connections Register (facts ABOUT a connection; never the secret) ----------
    CONN_FIELDS = ("service", "may_do", "used_by", "secret_name", "cost_model", "monthly_cap_usd", "expires", "revoke_how", "last_used", "status")

    def _conn_value(self, field, value):
        if field == "secret_name" and value and not re.fullmatch(r"[A-Z][A-Z0-9_]{2,63}", value):
            raise Refused("REFUSED: secret_name is the NAME of a Nimbuz Secret (like BK_GITHUB_TOKEN), never its value.")
        if field == "status" and value not in ("green", "amber", "red", "revoked"):
            raise Refused("REFUSED: status is green, amber, red or revoked.")
        if field == "monthly_cap_usd":
            return float(value or 0)
        if field in ("expires", "last_used"):
            if not value:
                return None
            try:
                return dt.date.fromisoformat(value)
            except Exception:
                raise Refused(f"REFUSED: {field} must be a date like 2027-02-15.")
        return value

    def register_connection(self, conn_id, fields, who):
        self._need(who, {"steward"}, "register_connection")
        if not re.fullmatch(r"CONN-[a-z0-9-]{2,40}", conn_id or ""):
            raise Refused("REFUSED: id must look like CONN-github.")
        unknown = set(fields) - set(self.CONN_FIELDS)
        if unknown:
            raise Refused(f"REFUSED: unknown field(s) {sorted(unknown)}.")
        if not fields.get("revoke_how") or not fields.get("may_do") or not fields.get("used_by"):
            raise Refused("REFUSED: if you can't say what a key may do, who uses it and how to kill it, don't connect it.")
        self._guard_secret(**{k: str(v) for k, v in fields.items()})
        if self._rows("MATCH (c:Connection {id:$id}) RETURN c.id", {"id": conn_id}):
            raise Refused(f"REFUSED: {conn_id} already exists — use update_connection.")
        fields = {**fields, "status": fields.get("status") or "amber"}
        vals = {f: self._conn_value(f, fields.get(f)) for f in self.CONN_FIELDS}
        sets = ", ".join(f"{f}:${f}" for f in self.CONN_FIELDS)
        self._tx([(f"CREATE (c:Connection {{id:$id, {sets}, updated_at:$at}}) RETURN c.id", {"id": conn_id, **vals, "at": now()}, 1)])
        self._log(who, "register_connection", {"id": conn_id, "service": vals["service"], "secret_name": vals["secret_name"]})
        return {"result": "REGISTERED", "id": conn_id}

    def update_connection(self, conn_id, field, value, who):
        self._need(who, {"steward"}, "update_connection")
        if field not in self.CONN_FIELDS:
            raise Refused(f"REFUSED: field must be one of {', '.join(self.CONN_FIELDS)}.")
        self._guard_secret(value=str(value))
        v = self._conn_value(field, value)
        self._tx([(f"MATCH (c:Connection {{id:$id}}) SET c.{field}=$v, c.updated_at=$at RETURN c.id", {"id": conn_id, "v": v, "at": now()}, 1)])
        self._log(who, "update_connection", {"id": conn_id, "field": field})
        return {"result": "UPDATED", "id": conn_id, "field": field}

    def list_connections(self):
        cols = ("id",) + self.CONN_FIELDS
        rows = self._rows("MATCH (c:Connection) RETURN " + ", ".join("c." + c for c in cols) + " ORDER BY c.id")
        today = dt.date.today()
        out = []
        for r in rows:
            d = {k: (str(v) if isinstance(v, (dt.date, dt.datetime)) else v) for k, v in zip(cols, r)}
            exp = r[cols.index("expires")]
            d["expires_in_days"] = (exp - today).days if exp else None
            out.append(d)
        return {"result": "OK", "total": len(out), "connections": out}

    # ---------- approvals register (rule 1) ----------
    # v0.5 (CONNECTOR-SCOPING §4): citizens can only REQUEST an approval. The decision is recorded ONLY through the
    # admin port, by the founder's page /bk-approve (bkinfra login helper behind Cloudflare Access) — no citizen token can
    # approve anything. approvals.jsonl holds three kinds of entries:
    #   {"type": "request",  "id": "R-…", item, draft_text, draft_sha256, requested_by, …}   (warden/steward)
    #   {"type": "decision", "id": "A-…", "request": "R-…", decision, decided_by: "founder", via: "bk-approve", …}
    #   no "type" = LEGACY (v0.4 and earlier: recorded by a citizen with record_approval; usually no text stored).
    def request_approval(self, item, draft_text, note, who):
        """Store the EXACT text the founder is asked to approve (canonical form, CANON) + its SHA-256. Nothing is approved
        here: the founder decides on /bk-approve."""
        self._need(who, {"warden", "steward"}, "request_approval")
        self._guard_disk()
        canon = canonical_text(draft_text) if (draft_text or "").strip() else ""
        if not canon:
            raise Refused("REFUSED: give draft_text — the EXACT text the founder is asked to approve (the post, the email, "
                          "the slate, or for an action the exact sentence describing it).")
        if len(canon) > APPROVAL_TEXT_MAX:
            raise Refused(f"REFUSED: draft_text is longer than {APPROVAL_TEXT_MAX} characters; split it.")
        if not (item or "").strip() or len(item) > 300:
            raise Refused("REFUSED: item is a short label (1–300 characters), e.g. 'LinkedIn post #2'.")
        self._guard_secret(item=item, note=note, draft_text=canon)
        if sum(1 for a in self._approval_views() if a["status"] == "pending") >= APPROVALS_PENDING_MAX:
            raise Refused(f"REFUSED: {APPROVALS_PENDING_MAX} approval requests are already waiting for the founder. "
                          "Ask the founder to clear /bk-approve first.")
        rid = "R-" + uuid.uuid4().hex[:8]
        h = hashlib.sha256(canon.encode("utf-8")).hexdigest()
        self.approvals.append({"type": "request", "id": rid, "at": now().isoformat() + "Z", "requested_by": who,
                               "item": item, "draft_text": canon, "draft_sha256": h, "canon": CANON, "note": note or ""})
        self._log(who, "request_approval", {"request": rid, "draft_sha256": h})
        return {"result": "REQUESTED", "id": rid, "draft_sha256": h, "canon": CANON,
                "next": "The founder approves or rejects it on /bk-approve (founder-only page). Nothing is approved until "
                        "list_approvals shows this request as approved with a decision id A-…."}

    def decide_approval(self, request_id, decision, founder, shown_sha256):
        """ADMIN PORT ONLY (the founder's /bk-approve page). shown_sha256 = hash of the text the page showed: a request
        can only be decided on exactly the text the founder saw."""
        if decision not in ("approved", "rejected"):
            raise Refused("REFUSED: decision is approved or rejected.")
        views = {a["id"]: a for a in self._approval_views()}
        r = views.get(request_id)
        if not r or r.get("type") != "request":
            raise Refused(f"REFUSED: there is no approval request '{request_id}'.")
        if r["status"] != "pending":
            raise Refused(f"REFUSED: request {request_id} is already {r['status']} ({r.get('decision_id')}).")
        if not re.fullmatch(r"[0-9a-f]{64}", shown_sha256 or "") or shown_sha256 != r["draft_sha256"]:
            raise Refused("REFUSED: the text shown is not the text requested (hash mismatch). Reload the page.")
        founder = re.sub(r"[^A-Za-z0-9@._+-]", "", founder or "")[:200] or "founder"
        aid = "A-" + uuid.uuid4().hex[:8]
        self.approvals.append({"type": "decision", "id": aid, "at": now().isoformat() + "Z", "request": request_id,
                               "decision": decision, "decided_by": "founder", "founder": founder, "via": "bk-approve",
                               "item": r["item"], "draft_text": r["draft_text"], "draft_sha256": r["draft_sha256"],
                               "canon": r.get("canon")})
        self._log("founder", "decide_approval", {"approval": aid, "request": request_id, "decision": decision})
        return {"result": "DECIDED", "id": aid, "request": request_id, "decision": decision}

    def _approvals(self):
        out = []
        if os.path.exists(self.approvals_path):
            for raw in open(self.approvals_path, "rb"):
                try:
                    out.append(json.loads(raw)["body"])
                except Exception:
                    pass
        return out

    def _approval_views(self):
        """Every entry with a status: pending / approved / rejected (requests), approved / rejected (founder decisions),
        legacy (recorded by a citizen before v0.5 — not a founder decision; 'legacy, text not stored' when no text)."""
        raw = self._approvals()
        decided = {a.get("request"): a for a in raw if a.get("type") == "decision"}
        out = []
        for a in raw:
            v = dict(a)
            t = a.get("type")
            if t == "request":
                d = decided.get(a.get("id"))
                v["status"] = d.get("decision") if d else "pending"
                if d:
                    v["decision_id"] = d.get("id")
            elif t == "decision":
                v["status"] = a.get("decision")
                v["founder_decision"] = True
            else:
                v["type"] = "legacy"
                v["status"] = "legacy"
                v["founder_decision"] = False
                v["legacy_note"] = ("legacy, text not stored" if not a.get("draft_text") else
                                    "legacy: recorded by a citizen before founder-only approvals (v0.5)")
            out.append(v)
        return out

    def check_approval(self, approval_id, who, text=""):
        """Recompute an approval's hash from its stored text; optionally compare a text you have (e.g. before a commit).
        Only a founder decision (A-… from /bk-approve, status approved) authorises anything."""
        self._need(who, {"warden", "steward", "librarian", "reviewer", "librarian_desk"}, "check_approval")
        a = next((x for x in self._approval_views() if x.get("id") == approval_id), None)
        if not a:
            raise Refused(f"REFUSED: there is no approval '{approval_id}'.")
        base = {"id": approval_id, "type": a["type"], "status": a["status"],
                "authorises": a["type"] == "decision" and a["status"] == "approved"}
        if a["type"] == "request" and a.get("decision_id"):
            base["decision_id"] = a["decision_id"]
        if not a.get("draft_text"):
            return {"result": "NO_TEXT", **base, "note": a.get("legacy_note") or "This entry has no stored text."}
        stored = hashlib.sha256(a["draft_text"].encode("utf-8")).hexdigest() == a.get("draft_sha256")
        out = {"result": "MATCH" if stored else "MISMATCH", **base, "draft_sha256": a.get("draft_sha256"),
               "canon": a.get("canon"), "stored_text_matches_hash": stored}
        if a["type"] == "legacy":
            out["note"] = a["legacy_note"]
        if (text or "").strip():
            same = hashlib.sha256(canonical_text(text).encode("utf-8")).hexdigest() == a.get("draft_sha256")
            out.update({"your_text_matches": same})
            if not same:
                out["result"] = "MISMATCH"
        return out

    def list_approvals(self, who, limit=20, status=""):
        self._need(who, {"warden", "steward", "librarian", "reviewer", "librarian_desk"}, "list_approvals")
        a = self._approval_views()
        if status:
            a = [x for x in a if x["status"] == status]
        return {"result": "OK", "total": len(a), "approvals": a[-max(1, min(int(limit), 200)):],
                "how": "Only entries with type 'decision' (A-…, via bk-approve) are founder decisions. 'legacy' entries were "
                       "recorded by a citizen before v0.5 and authorise nothing new."}

    def pending_approvals(self):
        """ADMIN PORT ONLY: the founder's page lists these with their full text."""
        views = self._approval_views()
        return {"pending": [a for a in views if a["status"] == "pending"],
                "recent": [a for a in views if a["type"] == "decision"][-10:]}

    # ---------- erasure route (DPDP): replace one diary line by a tombstone ----------
    def redact_diary_line(self, path, line, approval_id, reason, who):
        self._need(who, {"librarian"}, "redact_diary_line")
        self._guard_secret(reason=reason)
        ok = [a for a in self._approval_views() if a.get("id") == approval_id and a["type"] == "decision" and a["status"] == "approved"]
        if not ok:
            raise Refused("REFUSED: erasing diary content needs the founder's approval: a decision id A-… with status approved "
                          "from /bk-approve (request_approval first; legacy citizen-recorded approvals do not count).")
        root = os.path.realpath(self.diary_root)
        real = os.path.realpath(path)
        if not real.startswith(root + os.sep) or not real.endswith(".jsonl"):
            raise Refused("REFUSED: only diary files under the diary folder can be redacted.")
        try:
            orig = chain_redact(real, int(line))
        except (ValueError, OSError) as e:
            raise Refused(f"REFUSED: {e}")
        check = chain_verify(real)
        self._log(who, "redact_diary_line", {"file": os.path.relpath(real, root), "line": int(line), "approval": approval_id,
                                             "reason": reason, "original_body_sha256": orig, "chain_ok_after": check["ok"]})
        return {"result": "REDACTED", "original_body_sha256": orig, "chain_ok_after": check["ok"]}

    # ---------- stats + backups (admin endpoint only) ----------
    def stats(self):
        def one(q):
            return self._rows(q)[0][0]
        facts = sorted(self._rows("MATCH (f:Fact) RETURN f.id, f.status, f.text, f.instrument, f.level"))
        digest = hashlib.sha256("\n".join("|".join(str(x) for x in r) for r in facts).encode()).hexdigest()
        by = {}
        for r in facts:
            by[r[1]] = by.get(r[1], 0) + 1
        today = dt.date.today()
        open_tasks = self._rows("MATCH (t:Task {state:'open'}) RETURN t.due")
        conns = self._rows("MATCH (c:Connection) RETURN c.status, c.expires")
        return {"facts_total": len(facts), "facts_live": by.get("live", 0), "facts_superseded": by.get("superseded", 0),
                "facts_retired": by.get("retired", 0), "facts_digest": digest,
                "proposals_pending": one("MATCH (p:Proposal {state:'pending'}) RETURN count(p)"),
                "proposals_total": one("MATCH (p:Proposal) RETURN count(p)"),
                "sources": one("MATCH (s:Source) RETURN count(s)"),
                "tasks_open": len(open_tasks), "tasks_overdue": sum(1 for (d,) in open_tasks if d and d < today),
                "tasks_total": one("MATCH (t:Task) RETURN count(t)"),
                "connections": len(conns), "connections_red": sum(1 for s, _ in conns if s == "red"),
                "connections_expiring_14d": sum(1 for _, e in conns if e and 0 <= (e - today).days <= 14),
                "approvals": len(self._approvals()),
                "approvals_pending": sum(1 for a in self._approval_views() if a["status"] == "pending")}

    def snapshot(self, name=None):
        """EXPORT the graph + copy the change log and approvals into backups/<name>/. bk_backup.py adds the rest."""
        self._guard_disk()
        self.c.execute("CHECKPOINT")
        if not name:      # names are per second: a final snapshot right after a cycle must not collide (v0.3 fix)
            name = "snap-" + now().strftime("%Y%m%dT%H%M%SZ")
            while os.path.exists(os.path.join(self.backups, name)):
                time.sleep(0.2); name = "snap-" + now().strftime("%Y%m%dT%H%M%SZ")
        final = os.path.join(self.backups, name)
        tmp = os.path.join(self.backups, "." + name + ".tmp")
        shutil.rmtree(tmp, ignore_errors=True)
        os.makedirs(tmp)
        self.c.execute(f"EXPORT DATABASE '{os.path.join(tmp, 'library')}'")
        for fn in ("changes.jsonl", "approvals.jsonl"):
            src = os.path.join(self.dir, fn)
            if os.path.exists(src):
                shutil.copyfile(src, os.path.join(tmp, fn))
        st = self.stats()
        st["created_at"] = now().isoformat() + "Z"
        json.dump(st, open(os.path.join(tmp, "library-manifest.json"), "w"), indent=1)
        os.replace(tmp, final)
        return {"result": "SNAPSHOT", "dir": final, "stats": st}


# ---------- import / restore-test (used by bk_backup.py) ----------
def import_snapshot(snapshot_dir, db_path, schema_path, scratch=False):
    """Import snapshot_dir/library into a NEW database and compare with snapshot_dir/library-manifest.json.
    Raises on any mismatch; the target db only appears (atomic rename) after the check passed."""
    expect = json.load(open(os.path.join(snapshot_dir, "library-manifest.json")))
    tmp = db_path + ".importing"
    for p in (tmp, tmp + ".wal"):
        if os.path.isdir(p):
            shutil.rmtree(p)
        elif os.path.exists(p):
            os.remove(p)
    os.makedirs(os.path.dirname(os.path.abspath(db_path)), exist_ok=True)
    db = lb.Database(tmp)
    c = lb.Connection(db)
    try:
        c.execute(f"IMPORT DATABASE '{os.path.join(snapshot_dir, 'library')}'")
        c.execute(open(schema_path).read())
        lib = Library.__new__(Library)
        lib.c, lib.approvals_path = c, os.path.join(snapshot_dir, "approvals.jsonl")
        got = lib.stats()
        bad = [k for k in ("facts_total", "facts_live", "facts_superseded", "facts_retired", "facts_digest",
                           "proposals_total", "tasks_total", "connections") if got.get(k) != expect.get(k)]
        if bad:
            raise RuntimeError("restored Library does not match the snapshot manifest: " +
                               ", ".join(f"{k} {got.get(k)} != {expect.get(k)}" for k in bad))
        c.execute("CHECKPOINT")
    except Exception:
        c.close(); db.close()
        for p in (tmp, tmp + ".wal"):
            if os.path.exists(p):
                shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
        raise
    c.close(); db.close()
    if scratch:
        for p in (tmp, tmp + ".wal"):
            if os.path.exists(p):
                shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
        return got
    os.replace(tmp, db_path)
    if os.path.exists(tmp + ".wal"):
        os.replace(tmp + ".wal", db_path + ".wal")
    for fn in ("changes.jsonl", "approvals.jsonl"):
        src = os.path.join(snapshot_dir, fn)
        if os.path.exists(src):
            shutil.copyfile(src, os.path.join(os.path.dirname(os.path.abspath(db_path)), fn))
    return got


