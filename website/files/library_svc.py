    ap.add_argument("--restore-test", help="import this snapshot dir into a SCRATCH db and compare with its manifest")
    a = ap.parse_args(argv)
    if a.import_snapshot or a.restore_test:
        snap = a.import_snapshot or a.restore_test
        try:
            got = import_snapshot(snap, a.db if a.import_snapshot else a.db + ".restore-test", a.schema, scratch=bool(a.restore_test))
        except Exception as e:
            print(f"IMPORT FAILED: {e}", file=sys.stderr); return 4
        if a.restore_test and got["facts_total"] == 0:
            print("RESTORE TEST: FAIL — the snapshot restored 0 facts (nothing protected yet counts as a failure)", file=sys.stderr)
            return 5
        print(json.dumps({"result": "IMPORTED" if a.import_snapshot else "RESTORE TEST OK", **got}))
        return 0
    ids = identities_from_env()
    if not ids:
        print("library: no LIBRARY_TOKEN_<CITIZEN> tokens in env — every tool call will be refused", file=sys.stderr)
    lib = Library(a.db, a.schema, a.cards, a.citizens, a.backups, a.restored_marker,
                  int(os.environ.get("BK_MIN_FREE_MB", "500")), diary_root=a.diary)
    serve(lib, a.host, a.port, a.admin_port, ids, os.environ.get("LIBRARY_ADMIN_TOKEN", ""))
    return 0


